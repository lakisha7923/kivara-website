function buildTimesheet(
  partial: Omit<Timesheet, "date" | "year" | "month" | "week" | "weekLabel"> & {
    workDate: string;
  }
): Timesheet {
  const period = periodFromWorkDate(partial.workDate);
  return {
    ...partial,
    date: period.date,
    year: period.year,
    month: period.month,
    week: period.week,
    weekLabel: period.weekLabel,
  };
}

